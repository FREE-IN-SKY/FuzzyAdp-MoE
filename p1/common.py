class CSVLogger:
    """Write one row per epoch. Fields may differ between epochs (e.g. fields that exist only after the controller starts);
    when a new field appears the whole file is rewritten, and missing fields are left empty."""

    def __init__(self, path):
        self.path = Path(path)
        self.fields = []
        self.rows = []

    def log(self, row):
        row = {k: (json.dumps(v) if isinstance(v, (list, dict)) else v) for k, v in row.items()}
        self.rows.append(row)
        new = [k for k in row if k not in self.fields]
        if new:
            self.fields.extend(new)
            with open(self.path, "w", newline="") as f:
                w = csv.DictWriter(f, fieldnames=self.fields)
                w.writeheader()
                w.writerows(self.rows)
        else:
            with open(self.path, "a", newline="") as f:
                csv.DictWriter(f, fieldnames=self.fields).writerow(row)


def prepare_out_dir(out_dir, overwrite):
    out_dir = Path(out_dir).expanduser()
    if out_dir.exists() and any(out_dir.iterdir()) and not overwrite:
        raise SystemExit(f"[Error] Output directory is not empty: {out_dir}. Use a new directory for each run, or pass --overwrite")
    out_dir.mkdir(parents=True, exist_ok=True)
    return out_dir


def save_json(obj, path):
    with open(path, "w", encoding="utf-8") as f:
        json.dump(obj, f, ensure_ascii=False, indent=2)


def default_num_workers():
    return min(14, os.cpu_count() or 1)