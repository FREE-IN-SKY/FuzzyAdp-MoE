ENV_LOCK_DEFAULT = Path(__file__).resolve().parent.parent / "runs" / "env_lock.json"
ENV_CHECKED_KEYS = ("python", "torch", "torchvision", "timm", "numpy", "pillow", "scikit-fuzzy",
                    "cuda_runtime", "cudnn", "nvidia_driver", "gpu")  # other fields (kernel, git) are only recorded, not checked


def _run(cmd):
    try:
        return subprocess.run(cmd, capture_output=True, text=True, timeout=10, check=True).stdout.strip()
    except Exception:
        return None


def _pkg_version(name):
    try:
        return metadata.version(name)
    except metadata.PackageNotFoundError:
        return None


def collect_env():
    """Version information of the current environment. Checked items are in ENV_CHECKED_KEYS; kernel, git_commit, git_dirty are only recorded."""
    repo = Path(__file__).resolve().parent.parent
    driver = _run(["nvidia-smi", "--query-gpu=driver_version", "--format=csv,noheader"])
    commit = _run(["git", "-C", str(repo), "rev-parse", "HEAD"])
    dirty = _run(["git", "-C", str(repo), "status", "--porcelain", "--untracked-files=no"])
    return {
        "python": platform.python_version(), "torch": torch.__version__,
        "torchvision": _pkg_version("torchvision"), "timm": _pkg_version("timm"), "numpy": np.__version__,
        "pillow": _pkg_version("pillow"), "scikit-fuzzy": _pkg_version("scikit-fuzzy"),
        "cuda_runtime": torch.version.cuda,
        "cudnn": torch.backends.cudnn.version() if torch.backends.cudnn.is_available() else None,
        "nvidia_driver": driver.splitlines()[0].strip() if driver else None,
        "gpu": torch.cuda.get_device_name(0) if torch.cuda.is_available() else None,
        "kernel": platform.release(), "git_commit": commit,
        "git_dirty": None if dirty is None else bool(dirty),  # only uncommitted changes to tracked files
    }


def env_diff(lock, env):
    return [(k, lock.get(k), env.get(k)) for k in ENV_CHECKED_KEYS if lock.get(k) != env.get(k)]


def check_env(lock_path=ENV_LOCK_DEFAULT):
    """Check whether the current environment matches the lock and return the current environment. If the lock does not exist, create it from the current environment.
    Skip the check when lock_path is "none" (only for smoke tests). Call before creating the output directory."""
    env = collect_env()
    if str(lock_path).lower() == "none":
        print("[Warning] --env-lock none: environment check skipped (smoke tests only)")
        return env
    lock_path = Path(lock_path).expanduser()
    if not lock_path.exists():
        lock_path.parent.mkdir(parents=True, exist_ok=True)
        save_json({**{k: env[k] for k in ENV_CHECKED_KEYS},
                   "created_utc": datetime.now(timezone.utc).isoformat(timespec="seconds")}, lock_path)
        print(f"[Info] {lock_path} not found; created it from the current environment")
        return env
    diff = env_diff(json.loads(lock_path.read_text(encoding="utf-8")), env)
    if diff:
        lines = "\n".join(f"  {k}: locked {a!r}, current {b!r}" for k, a, b in diff)
        raise SystemExit(f"[Error] The environment does not match {lock_path}:\n{lines}\n"
                         f"If the upgrade is intentional, run: python p1/env_lock.py --update --reason \"<reason>\"")
    return env


