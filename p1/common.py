def classification_metrics(y_true, y_pred, num_classes, pi):
    """Return overall accuracy, accuracy A_pi weighted by the target distribution pi, balanced accuracy, Macro-F1, and per-class metrics.

    A_pi = sum_c pi_c * recall_c, i.e. compute per-class accuracy first, then weight by pi.
    If a class has no samples in the validation set, it is excluded from balanced accuracy and Macro-F1, counted as 0 in A_pi, and a notice is printed.
    """
    y_true = np.asarray(y_true)
    y_pred = np.asarray(y_pred)
    cm = np.zeros((num_classes, num_classes), dtype=np.int64)
    np.add.at(cm, (y_true, y_pred), 1)
    support = cm.sum(1)
    tp = np.diag(cm)
    pred_count = cm.sum(0)
    with np.errstate(divide="ignore", invalid="ignore"):
        recall = np.where(support > 0, tp / support, np.nan)
        precision = np.where(pred_count > 0, tp / pred_count, 0.0)
        f1 = np.where((precision + np.nan_to_num(recall)) > 0,
                      2 * precision * np.nan_to_num(recall) / (precision + np.nan_to_num(recall)), 0.0)
    present = support > 0
    out = {
        "acc": float(tp.sum() / max(len(y_true), 1)),
        "acc_pi": float(np.sum(pi * np.nan_to_num(recall))),
        "balanced_acc": float(np.nanmean(recall[present])) if present.any() else float("nan"),
        "macro_f1": float(np.mean(f1[present])) if present.any() else float("nan"),
        "missing_classes": [int(c) for c in np.where(~present)[0]],
        "per_class": {
            "support": support.tolist(),
            "recall": [None if np.isnan(r) else float(r) for r in recall],
            "precision": precision.astype(float).tolist(),
            "f1": f1.astype(float).tolist(),
        },
        "confusion_matrix": cm.tolist(),
    }
    return out


def weighted_expert_usage(per_class_expert_count, pi, top_k):
    """Combine per-class expert usage rates weighted by the target distribution pi; return percentages (length N_e, summing to 100).

    u_e = sum_c pi_c * M_ce / (top_k * n_c), where M_ce is the number of times samples of class c selected expert e.
    If a class has no samples in the validation set, it is excluded, and pi of the remaining classes is renormalized.
    """
    m = np.asarray(per_class_expert_count, dtype=np.float64)  # (C, N_e)
    n_c = m.sum(1) / top_k
    present = n_c > 0
    w = pi * present
    w = w / w.sum()
    usage = np.zeros(m.shape[1])
    for c in np.where(present)[0]:
        usage += w[c] * m[c] / (top_k * n_c[c])
    return usage * 100.0


def mixture(logits, sel, w, mode="mix"):
    """Recombine the expert outputs by routing (numpy, for offline analysis). logits (N, E, C), sel (N, k) selected experts, w (N, k) normalized weights -> (N, C).
    mix: weighted logits; mixprob: log of the mixture probability, log Σ_k w_k softmax(logits_k). Consistent with train_moe.prediction_logits."""
    picked = np.take_along_axis(logits, sel[:, :, None], 1)  # (N, k, C)
    if mode == "mixprob":
        m = picked.max(2, keepdims=True)
        log_p = picked - m - np.log(np.exp(picked - m).sum(2, keepdims=True))  # log_softmax
        z = np.log(w)[:, :, None] + log_p
        zm = z.max(1, keepdims=True)
        return (zm + np.log(np.exp(z - zm).sum(1, keepdims=True))).squeeze(1)
    return (picked * w[:, :, None]).sum(1)


