class TrainDiagnostics:
    """Per-epoch gradient norm, parameter norm, relative update size and number of GradScaler-skipped steps, per parameter group.

    Read-only: gradient norms are converted back to the original scale with the current scale factor, without calling scaler.unscale_; parameter snapshots are used only to compute updates
    and are not written back to the model. Statistics are accumulated on the GPU and synchronized at the end of the epoch.
    - epoch net relative displacement ||θ_epoch_end − θ_epoch_start|| / ||θ_epoch_start|| (diag_update_*), not the per-step step size;
    - within-epoch mean and maximum of the per-step relative update ||θ_{t+1} − θ_t|| / ||θ_t|| (diag_step_update_*);
    - per-step angle change, in degrees, of each column (each expert direction) of every parameter in angle_params (diag_step_angle_*).
    Steps whose gradients contain inf/NaN (skipped by GradScaler) are excluded from the gradient and per-step update statistics and only counted as skipped steps.
    Call order: start_epoch → (each step) backward → after_backward → scaler.step/update → after_step → end_epoch
    """

    def __init__(self, groups, angle_params=None):
        self.groups = {k: [p for p in ps if p.requires_grad] for k, ps in groups.items()}
        self.angle_params = angle_params or {}  # {name: parameter}; angle change computed per column (dim=0 direction)
        self.prev = {k: [torch.empty_like(p) for p in ps] for k, ps in self.groups.items()}  # parameters before each step's update
        self.angle_prev = {k: torch.empty_like(p) for k, p in self.angle_params.items()}

    @torch.no_grad()
    def start_epoch(self, scaler):
        dev = next(iter(self.groups.values()))[0].device
        self.snapshot = {k: [p.detach().clone() for p in ps] for k, ps in self.groups.items()}
        self.g_sum = {k: torch.zeros((), device=dev) for k in self.groups}
        self.g_max = {k: torch.zeros((), device=dev) for k in self.groups}
        self.g_cnt = {k: torch.zeros((), device=dev) for k in self.groups}
        self.s_sum = {k: torch.zeros((), device=dev) for k in self.groups}
        self.s_max = {k: torch.zeros((), device=dev) for k in self.groups}
        self.a_sum = {k: torch.zeros((), device=dev) for k in self.angle_params}
        self.a_max = {k: torch.zeros((), device=dev) for k in self.angle_params}
        self.n_steps = 0  # number of steps not skipped
        self.skipped = 0
        self.scale = scaler.get_scale()  # 1.0 when GradScaler is not enabled; the scale factor changes only in scaler.update()

    @torch.no_grad()
    def after_backward(self):
        inv = 1.0 / self.scale
        for k, ps in self.groups.items():
            grads = [p.grad for p in ps if p.grad is not None]
            if not grads:  # e.g. experts not selected in this batch
                continue
            g = get_total_norm(grads).float() * inv
            ok = torch.isfinite(g)
            g = torch.where(ok, g, torch.zeros_like(g))
            self.g_sum[k] += g
            self.g_cnt[k] += ok.float()
            self.g_max[k] = torch.maximum(self.g_max[k], g)
        for k, ps in self.groups.items():  # save the parameters before the update (parameters do not change between backward and scaler.step)
            torch._foreach_copy_(self.prev[k], [p.detach() for p in ps])
        for k, p in self.angle_params.items():
            self.angle_prev[k].copy_(p.detach())

    @torch.no_grad()
    def after_step(self, scaler):
        new = scaler.get_scale()
        skipped = new < self.scale  # GradScaler lowers the scale factor only when the gradients contain inf/NaN, i.e. when the step is skipped
        self.scale = new
        if skipped:
            self.skipped += 1
            return
        self.n_steps += 1
        for k, ps in self.groups.items():
            cur = [p.detach() for p in ps]
            r = get_total_norm(torch._foreach_sub(cur, self.prev[k])) / get_total_norm(self.prev[k]).clamp_min(1e-12)
            self.s_sum[k] += r
            self.s_max[k] = torch.maximum(self.s_max[k], r)
        for k, p in self.angle_params.items():
            a, b = self.angle_prev[k].float(), p.detach().float()
            cos = (a * b).sum(0) / (a.norm(dim=0) * b.norm(dim=0)).clamp_min(1e-12)
            ang = torch.rad2deg(torch.acos(cos.clamp(-1.0, 1.0)))  # angle change of each column (each expert direction)
            self.a_sum[k] += ang.mean()
            self.a_max[k] = torch.maximum(self.a_max[k], ang.max())

    @torch.no_grad()
    def end_epoch(self):
        out = {}
        for k, ps in self.groups.items():
            p_old = get_total_norm(self.snapshot[k]).item()
            delta = get_total_norm([p.detach() - s for p, s in zip(ps, self.snapshot[k])]).item()
            cnt = self.g_cnt[k].item()
            out[f"diag_grad_{k}_mean"] = self.g_sum[k].item() / cnt if cnt else float("nan")
            out[f"diag_grad_{k}_max"] = self.g_max[k].item()
            out[f"diag_param_{k}"] = get_total_norm([p.detach() for p in ps]).item()
            out[f"diag_update_{k}"] = delta / p_old if p_old > 0 else float("nan")
            out[f"diag_step_update_{k}_mean"] = self.s_sum[k].item() / self.n_steps if self.n_steps else float("nan")
            out[f"diag_step_update_{k}_max"] = self.s_max[k].item()
        for k in self.angle_params:
            out[f"diag_step_angle_{k}_mean"] = self.a_sum[k].item() / self.n_steps if self.n_steps else float("nan")
            out[f"diag_step_angle_{k}_max"] = self.a_max[k].item()
        out["diag_amp_skipped"] = self.skipped
        out["diag_amp_scale"] = self.scale
        self.snapshot = None
        return out


