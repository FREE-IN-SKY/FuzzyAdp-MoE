def load_manifest(path):
    """Read the manifest.json generated by make_subset.py and return (class_names, pi).

    class_names is ordered by class_idx; pi is the training-subset target distribution, in the same order as class_names.
    """
    with open(path, encoding="utf-8") as f:
        m = json.load(f)
    class_to_idx = m["class_to_idx"]
    class_names = [None] * len(class_to_idx)
    for name, idx in class_to_idx.items():
        class_names[idx] = name
    pi_values = m["target_distribution_pi"]["values"]
    pi = np.array([pi_values[name] for name in class_names], dtype=np.float64)
    if abs(pi.sum() - 1.0) > 1e-9:
        raise ValueError(f"The sum of pi in the manifest is {pi.sum()}, expected 1")
    return class_names, pi


class CSVImageDataset(Dataset):
    """Read the file list output by make_subset.py (path, class_name, class_idx, date)."""

    def __init__(self, root, list_csv, class_names, transform=None):
        self.root = Path(root).expanduser()
        self.transform = transform
        self.samples = []
        with open(list_csv, newline="") as f:
            for r in csv.DictReader(f):
                idx = int(r["class_idx"])
                if class_names[idx] != r["class_name"]:
                    raise ValueError(f"{list_csv}: class_idx does not match the manifest: {r}")
                self.samples.append((r["path"], idx, r["date"]))
        if not self.samples:
            raise ValueError(f"{list_csv} is empty")
        self.targets = [s[1] for s in self.samples]

    def __len__(self):
        return len(self.samples)

    def __getitem__(self, i):
        rel, label, _ = self.samples[i]
        with Image.open(self.root / rel) as img:
            img = img.convert("RGB")
        if self.transform is not None:
            img = self.transform(img)
        return img, label, i


