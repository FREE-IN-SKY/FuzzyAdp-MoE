def build_transforms(aug):
    """aug='A': original augmentation; aug='B': augmentation aligned with the original RSCD paper (horizontal flip, scaling, small color jitter)."""
    normalize = transforms.Normalize(IMAGENET_MEAN, IMAGENET_STD)
    if aug == "A":
        train_tf = transforms.Compose([
            transforms.Resize((INPUT_SIZE, INPUT_SIZE)),
            transforms.RandomHorizontalFlip(p=0.5),
            transforms.RandomRotation(10),
            transforms.RandomVerticalFlip(p=0.3),
            transforms.ColorJitter(brightness=0.4, contrast=0.4, saturation=0.3, hue=0.10),
            transforms.RandomAffine(degrees=0, translate=(0.1, 0.1), scale=(0.9, 1.1)),
            transforms.GaussianBlur(kernel_size=3, sigma=(0.1, 2.0)),
            transforms.RandomPerspective(distortion_scale=0.3, p=0.5),
            transforms.ToTensor(),
            transforms.RandomErasing(p=0.4, scale=(0.02, 0.15), ratio=(0.3, 3.3)),
            normalize,
        ])
    elif aug == "B":
        train_tf = transforms.Compose([
            transforms.Resize((INPUT_SIZE, INPUT_SIZE)),
            transforms.RandomHorizontalFlip(p=0.5),
            transforms.RandomAffine(degrees=0, scale=(0.9, 1.1)),
            transforms.ColorJitter(brightness=0.2, contrast=0.2, hue=0.02),
            transforms.ToTensor(),
            normalize,
        ])
    else:
        raise ValueError(f"Unknown augmentation mode: {aug}")
    eval_tf = transforms.Compose([
        transforms.Resize((INPUT_SIZE, INPUT_SIZE)),
        transforms.ToTensor(),
        normalize,
    ])
    return train_tf, eval_tf


