# random seeds
# ======================================================================
def set_seed(seed):
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    torch.cuda.manual_seed_all(seed)
    torch.backends.cudnn.deterministic = True
    torch.backends.cudnn.benchmark = False


def worker_init_fn(worker_id):
    # each worker's torch seed is set by the DataLoader generator; sync numpy and random here
    seed = torch.initial_seed() % 2 ** 32
    np.random.seed(seed)
    random.seed(seed)


def make_loader(dataset, batch_size, shuffle, num_workers, seed):
    g = torch.Generator()
    g.manual_seed(seed)
    return torch.utils.data.DataLoader(
        dataset,
        batch_size=batch_size,
        shuffle=shuffle,
        num_workers=num_workers,
        pin_memory=torch.cuda.is_available(),
        generator=g,
        worker_init_fn=worker_init_fn,
        persistent_workers=num_workers > 0,
    )


# ======================================================================
# learning-rate schedule: linear warmup + cosine annealing, updated per iteration
# ======================================================================
def build_scheduler(optimizer, steps_per_epoch, epochs, warmup_epochs, min_lr):
    total = steps_per_epoch * epochs
    warm = steps_per_epoch * warmup_epochs
    if warm >= total:
        raise ValueError("The number of warmup epochs must be less than the total number of epochs")
    cosine = CosineAnnealingLR(optimizer, T_max=total - warm, eta_min=min_lr)
    if warm == 0:
        return cosine
    warmup = LinearLR(optimizer, start_factor=0.01, end_factor=1.0, total_iters=warm)
    return SequentialLR(optimizer, schedulers=[warmup, cosine], milestones=[warm])


